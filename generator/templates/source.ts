export function detail(r: Resource): string {
  const enumLabels = enums(r).map((f) => `${upperSnake(f.name)}_LABELS`);
  const imports = [
    `import { useEffect, useState } from "react";`,
    r.ops.delete ? `import { useRouter } from "next/navigation";` : "",
    ``,
    `import { DetailLayout } from "@/components/layouts/kit-layouts";`,
    r.ops.delete ? `import { ConfirmDelete } from "@/components/patterns/confirm-delete";` : "",
    `import { EmptyState } from "@/components/patterns/empty-state";`,
    `import { ErrorState } from "@/components/patterns/error-state";`,
    r.ops.update ? "" : `import { FieldList } from "@/components/patterns/field-list";`,
    `import { Card } from "@/components/ui/card";`,
    `import { Skeleton } from "@/components/ui/skeleton";`,
    `import { TextLink } from "@/components/ui/text-link";`,
    `import { ${[...(r.ops.update ? [] : enumLabels), `type ${r.Name}Dto`].join(", ")} } from "@/contracts/${r.kebab}";`,
    `import { ApiClientError, errorMessage } from "@/lib/api-client";`,
    `import { ${r.ops.delete ? `delete${r.Name}, ` : ""}get${r.Name} } from "@/features/${r.pluralKebab}/api";`,
    r.ops.update ? `import { ${r.Name}Form } from "./${r.kebab}-form";` : "",
  ].filter((line, i, all) => line !== "" || (i > 0 && all[i - 1] !== ""));

  const body = r.ops.update
    ? `<${r.Name}Form mode="edit" item={item} onSaved={(saved) => setState({ status: "ready", item: saved })} />`
    : `<FieldList
          items={${fieldListItems(r, r.fields, "item")}}
        />`;

  return `${header(r)}"use client";

${imports.join("\n")}

type DetailState =
  | { status: "loading" }
  | { status: "not-found" }
  | { status: "error"; message: string }
  | { status: "ready"; item: ${r.Name}Dto };

// Layout: detail${r.ops.update ? "-with-edit-form" : ""}
export function ${r.Name}Detail({ id }: { id: string }) {
${r.ops.delete ? "  const router = useRouter();\n" : ""}  const [state, setState] = useState<DetailState>({ status: "loading" });
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    let active = true;
    get${r.Name}(id)
      .then((item) => active && setState({ status: "ready", item }))
      .catch((error: unknown) => {
        if (!active) return;
        if (error instanceof ApiClientError && error.status === 404) setState({ status: "not-found" });
        else setState({ status: "error", message: errorMessage(error, ${lit(`Unable to load the ${r.labelLower}.`)}) });
      });
    return () => {
      active = false;
    };
  }, [id, attempt]);

  const back = <TextLink text=${lit(`Back to ${r.pluralLabelLower}`)} href=${lit(`/${r.pluralKebab}`)} />;

  if (state.status === "loading") {
    return (
      <div role="status" aria-label=${lit(`Loading ${r.labelLower}`)}>
        <Skeleton kind="card" />
      </div>
    );
  }

  if (state.status === "not-found") {
    return (
      <div className="space-y-4">
        <EmptyState title=${lit(`${r.label} not found`)} description="It may have been deleted, or it belongs to another account." />
        {back}
      </div>
    );
  }

  if (state.status === "error") {
    return (
      <ErrorState
        message={state.message}
        onRetry={() => {
          setState({ status: "loading" });
          setAttempt((current) => current + 1);
        }}
      />
    );
  }

  const { item } = state;

  return (
    <DetailLayout
      title={item.${r.title.name}}
      description={\`Last updated \${new Date(item.updatedAt).toLocaleString()}\`}
      actions={
        <div className="flex items-center gap-2">
          {back}
${
  r.ops.delete
    ? `          <ConfirmDelete
            itemName={item.${r.title.name}}
            resourceLabel=${lit(r.labelLower)}
            onConfirm={() => delete${r.Name}(item.id)}
            onDeleted={() => router.push(${lit(`/${r.pluralKebab}`)})}
            describeError={(error) => errorMessage(error, ${lit(`Unable to delete the ${r.labelLower}.`)})}
          />
`
    : ""
}        </div>
      }
    >
      <Card title="Details">
        ${body}
      </Card>
    </DetailLayout>
  );
}
`;
}

