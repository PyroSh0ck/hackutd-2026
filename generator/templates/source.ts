// ---------- service ----------

export function service(r: Resource): string {
  const types = [`Create${r.Name}Input`, `List${r.Plural}Query`, `${r.Name}Dto`];
  if (r.ops.update) types.push(`Update${r.Name}Input`);
  for (const f of enums(r)) types.push(enumType(f));
  const dateHelpers = has(r, "date") ? [`fromIsoDate`, `toIsoDate`] : [];
  const rel = r.relations;
  const rowType = rel.length ? `Row` : r.Name;
  const inc = rel.length ? ", include" : "";
  const includeBlock = rel.length
    ? `
// Parent records are included so the DTO can show their title.
const include = {
${rel.map((f) => `  ${f.relation}: { select: { id: true, ${f.parent!.titleName}: true } },`).join("\n")}
} satisfies Prisma.${r.Name}Include;

type Row = Prisma.${r.Name}GetPayload<{ include: typeof include }>;
`
    : "";
  const parentChecks = (source: string) =>
    rel
      .map(
        (f) => `  if (${source}.${f.name} != null) await assertOwnedParent(prisma.${f.parent!.name}, ownerId, ${source}.${f.name}, ${lit(f.name)}, ${lit(`Choose a valid ${f.label.toLowerCase()}.`)});`,
      )
      .join("\n");

  const createData = r.fields
    .map((f) => {
      const v = `input.${f.name}`;
      if (f.nullable) {
        return f.type === "date"
          ? `      ${f.name}: ${v} == null ? null : fromIsoDate(${v}),`
          : `      ${f.name}: ${v} ?? null,`;
      }
      if (f.createOptional) return `      ...(${v} !== undefined ? { ${f.name}: ${toDataExpr(f, v)} } : {}),`;
      return `      ${f.name}: ${toDataExpr(f, v)},`;
    })
    .join("\n");

  const search = r.searchFields
    .map((f) => `            { ${f.name}: { contains: query.q, mode: "insensitive" } },`)
    .join("\n");

  const itemFns = `
export async function get${r.Name}(ownerId: string, id: string): Promise<${r.Name}Dto> {
  const row = await prisma.${r.name}.findFirst({ where: { id, ownerId }${inc} });
  if (!row) throw new NotFoundError(${lit(r.label)});
  return to${r.Name}Dto(row);
}
`;

  const updateFn = `
export async function update${r.Name}(ownerId: string, id: string, input: Update${r.Name}Input): Promise<${r.Name}Dto> {
${parentChecks("input")}
  const data: Prisma.${r.Name}${rel.length ? "UncheckedUpdateManyInput" : "UpdateManyMutationInput"} = {};
${r.fields
  .map((f) => `  if (input.${f.name} !== undefined) data.${f.name} = ${toDataExpr(f, `input.${f.name}`)};`)
  .join("\n")}

  const { count } = await prisma.${r.name}.updateMany({ where: { id, ownerId }, data });
  if (count === 0) throw new NotFoundError(${lit(r.label)});

  return get${r.Name}(ownerId, id);
}
`;

  const deleteFn = `
export async function delete${r.Name}(ownerId: string, id: string): Promise<void> {
  const { count } = await prisma.${r.name}.deleteMany({ where: { id, ownerId } });
  if (count === 0) throw new NotFoundError(${lit(r.label)});
}
`;

  return `${header(r)}import "server-only";

import type { ${rel.length ? "" : `${r.Name}, `}Prisma } from "@/generated/prisma/client";
import type { ${joinImports(types)} } from "@/contracts/${r.kebab}";
${dateHelpers.length ? `import { ${dateHelpers.join(", ")} } from "@/contracts/fields";\n` : ""}import { pageMeta, type PageMeta } from "@/contracts/pagination";
import { prisma } from "@/server/db";
${r.hasItemRoute ? `import { NotFoundError } from "@/server/http/errors";\n` : ""}${rel.length ? `import { assertOwnedParent } from "@/server/http/ownership";\n` : ""}
// Every query is scoped by ownerId from the authenticated session.
${includeBlock}
function to${r.Name}Dto(row: ${rowType}): ${r.Name}Dto {
  return {
    id: row.id,
${r.fields.map((f) => `    ${f.name}: ${toDtoExpr(f)},`).join("\n")}
${rel.map((f) => `    ${f.relation}: ${f.nullable ? `row.${f.relation} ? { id: row.${f.relation}.id, label: row.${f.relation}.${f.parent!.titleName} } : null` : `{ id: row.${f.relation}.id, label: row.${f.relation}.${f.parent!.titleName} }`},`).join("\n")}
    createdAt: row.createdAt.toISOString(),
    updatedAt: row.updatedAt.toISOString(),
  };
}

export async function create${r.Name}(ownerId: string, input: Create${r.Name}Input): Promise<${r.Name}Dto> {
${parentChecks("input")}
  const row = await prisma.${r.name}.create({
    data: {
${createData}
      ownerId,
    },${rel.length ? "\n    include," : ""}
  });
  return to${r.Name}Dto(row);
}

export async function list${r.Plural}(
  ownerId: string,
  query: List${r.Plural}Query = { page: 1, pageSize: ${r.pageSize} },
): Promise<{ items: ${r.Name}Dto[]; meta: PageMeta }> {
  const where: Prisma.${r.Name}WhereInput = {
    ownerId,
${rel.map((f) => `    ...(query.${f.name} ? { ${f.name}: query.${f.name} } : {}),`).join("\n")}
    ...(query.q
      ? {
          OR: [
${search}
          ],
        }
      : {}),
  };

  const [total, rows] = await prisma.$transaction([
    prisma.${r.name}.count({ where }),
    prisma.${r.name}.findMany({
      where,
      orderBy: [{ createdAt: "desc" }, { id: "desc" }],
      skip: (query.page - 1) * query.pageSize,
      take: query.pageSize,${rel.length ? "\n      include," : ""}
    }),
  ]);

  return { items: rows.map(to${r.Name}Dto), meta: pageMeta(query.page, query.pageSize, total) };
}
${r.ops.detail || r.ops.update ? itemFns : ""}${r.ops.update ? updateFn : ""}${r.ops.delete ? deleteFn : ""}`;
}

