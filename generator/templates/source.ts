export const header = (r: Resource) =>
  `// Generated by the feature generator from specs/${r.name}.json. You own this file:\n// edit freely. \`pnpm gen\` never overwrites edited files.\n`;

const pascalOf = (s: string) => s[0].toUpperCase() + s.slice(1);
const enums = (r: Resource) => r.fields.filter((f): f is Extract<Field, { type: "enum" }> => f.type === "enum");
const has = (r: Resource, ...types: Field["type"][]) => r.fields.some((f) => types.includes(f.type));
const joinImports = (names: string[]) => [...new Set(names)].sort().join(", ");

// ---------- contracts ----------

export function contract(r: Resource): string {
  const helpers: string[] = [];
  if (r.fields.some((f) => f.nullable)) helpers.push("optionalValue");
  if (has(r, "int", "decimal")) helpers.push("numberValue");
  if (has(r, "decimal")) helpers.push("hasAtMostDecimals");
  if (has(r, "date")) helpers.push("isoDate");

  const enumBlocks = enums(r)
    .map((f) => {
      const U = upperSnake(f.name);
      return [
        `export const ${U}_VALUES = [${f.values.map((v) => lit(v.value)).join(", ")}] as const;`,
        `export type ${enumType(f)} = (typeof ${U}_VALUES)[number];`,
        `export const ${U}_LABELS: Record<${enumType(f)}, string> = {`,
        ...f.values.map((v) => `  ${v.value}: ${lit(v.label)},`),
        `};`,
      ].join("\n");
    })
    .join("\n\n");

  const update = r.ops.update
    ? `
export const Update${r.Name}Schema = z
  .object({
${r.fields.map((f) => `    ${f.name}: ${zodUpdate(f)},`).join("\n")}
  })
  .strict()
  .refine((value) => Object.values(value).some((field) => field !== undefined), {
    message: "Provide at least one field to update.",
  });
`
    : "";

  return `${header(r)}import { z } from "zod";
${helpers.length ? `import { ${joinImports(helpers)} } from "@/contracts/fields";\n` : ""}import { ListQuerySchema, PageMetaSchema${r.relations.length ? ", ResourceIdSchema" : ""} } from "@/contracts/pagination";
${enumBlocks ? `\n${enumBlocks}\n` : ""}
export const Create${r.Name}Schema = z
  .object({
${r.fields.map((f) => `    ${f.name}: ${zodCreate(f)},`).join("\n")}
  })
  .strict();
${update}
export const List${r.Plural}QuerySchema = ${
    r.relations.length
      ? `ListQuerySchema.extend({
${r.relations.map((f) => `  ${f.name}: ResourceIdSchema.optional(),`).join("\n")}
}).strict()`
      : "ListQuerySchema"
  };

export const ${r.Name}DtoSchema = z.object({
  id: z.string(),
${r.fields.map((f) => `  ${f.name}: ${zodDto(f)},`).join("\n")}
${r.relations.map((f) => `  ${f.relation}: z.object({ id: z.string(), label: z.string() })${f.nullable ? ".nullable()" : ""},`).join("\n")}
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
});

export const ${r.Name}ResponseSchema = z.object({ data: ${r.Name}DtoSchema });

export const List${r.Plural}ResponseSchema = z.object({
  data: z.array(${r.Name}DtoSchema),
  meta: PageMetaSchema,
});

export type Create${r.Name}Input = z.infer<typeof Create${r.Name}Schema>;
${r.ops.update ? `export type Update${r.Name}Input = z.infer<typeof Update${r.Name}Schema>;\n` : ""}export type List${r.Plural}Query = z.infer<typeof List${r.Plural}QuerySchema>;
export type ${r.Name}Dto = z.infer<typeof ${r.Name}DtoSchema>;
`;
}

