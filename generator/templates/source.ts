/** `children`: back-relation lines previously inserted by child features (kept on regeneration). */
export function prismaModel(r: Resource, children: string[] = []): string {
  const lines = [
    `id String @id @default(cuid())`,
    ...r.fields.map(prismaField),
    `createdAt DateTime @default(now())`,
    `updatedAt DateTime @updatedAt`,
    ``,
    `ownerId String`,
    `owner User @relation(fields: [ownerId], references: [id], onDelete: Cascade)`,
    ``,
    `@@index([ownerId, createdAt])`,
    ...r.relations.map((f) => `@@index([${f.name}])`),
    ``,
    `// generator:relations (child back-relations are inserted below this line)`,
    ...children.map((line) => line.trim()),
  ];
  return `// Generated by the feature generator from specs/${r.name}.json.
// Changing this model requires a migration: see generator/README.md.
model ${r.Name} {
${lines.flatMap((line) => line.split("\n")).map((line) => (line ? `  ${line}` : "")).join("\n")}
}
`;
}

